export function layoutById(id: string): BoardShape {
  const layout = LAYOUTS.find((l) => l.id === id);
  if (!layout) throw new Error(`Unknown layout ${id}`);
  return layout;
}

/** The layout as one entry per cell (row by row): 1 where the cell starts filled. */
export function layoutCells(layout: BoardShape, cols: number, rows: number): Uint8Array {
  if (layout.rows.length !== rows || layout.rows.some((r) => r.length !== cols)) {
    throw new Error(`Layout ${layout.id} is not ${cols} × ${rows}`);
  }
  const cells = new Uint8Array(cols * rows);
  layout.rows.forEach((row, y) => {
    for (let x = 0; x < cols; x++) if (row[x] === '#') cells[y * cols + x] = 1;
  });
  return cells;
}
